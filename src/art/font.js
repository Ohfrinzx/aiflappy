// Wider variants with 2px gaps so `bold` doesn't fill them in.
const BOLD_SAFE = {
  m: ['.......', '.......', '######.', '#..#..#', '#..#..#', '#..#..#', '#..#..#'],
  w: ['.......', '.......', '#..#..#', '#..#..#', '#..#..#', '#..#..#', '.##.##.'],
  M: ['#.....#', '##...##', '#.#.#.#', '#..#..#', '#.....#', '#.....#', '#.....#'],
  W: ['#.....#', '#.....#', '#.....#', '#..#..#', '#..#..#', '#.#.#.#', '.#...#.'],
};

export const FONTS = { big: { glyphs: BIG, height: 9, base: 7 }, small: { glyphs: SMALL, height: 5, base: 5 } };

// Lays out text into a Pix mask (solid = 'x'). `bold` thickens strokes by
// extending every dot right (and down when boldY) by that many pixels.
function layout(text, font, cell, spacing, bold = 0, boldY = 0) {
  const f = FONTS[font];
  const pickGlyph = (ch) =>
    (bold && font === 'big' && BOLD_SAFE[ch]) || f.glyphs[ch] || f.glyphs[ch.toUpperCase()] || f.glyphs[' '];
  const glyphs = [...text].map(pickGlyph);
  const hasDesc = glyphs.some((g) => g.length > f.base);
  const rows = hasDesc ? f.height : f.base;
  const adv = (g) => g[0].length * cell + bold + spacing;
  const width = glyphs.reduce((s, g) => s + adv(g), -spacing);
  const pix = new Pix(Math.max(1, width), rows * cell + boldY);
  let x = 0;
  for (const g of glyphs) {
    g.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++) {
        if (row[gx] === '#') pix.rect(x + gx * cell, gy * cell, cell + bold, cell + boldY, 'x');
      }
    });
    x += adv(g);
  }
  return { pix, capH: f.base * cell + boldY };
}

/**
 * Renders styled text to a canvas.
 * opts: font ('big'|'small'), cell (px per font dot), spacing, fill, fillBottom
 *       (two-tone lower half), inner (1st outline), outer (2nd outline),
 *       shadow (drop shadow color), bold/boldY (stroke thickening), scale (canvas upscale, renderText only).
 */
export function renderText(text, opts = {}) {
  return textPix(text, opts).toCanvas(opts.scale ?? 2);
}

// Same as renderText but returns the Pix (for compositing into other art).
export function textPix(text, opts = {}) {
  const {
    font = 'big',
    cell = 1,
    spacing = 1,
    fill = '#fff',
    fillBottom = null,
    inner = null,
    outer = null,
    shadow = null,
    bold = 0,
    boldY = 0,
  } = opts;
  const { pix: mask, capH } = layout(text, font, cell, spacing, bold, boldY);
  const pad = (inner ? 1 : 0) + (outer ? 1 : 0) + (shadow ? 1 : 0);
  const out = new Pix(mask.w + pad * 2, mask.h + pad * 2);
  const glyph = new Pix(out.w, out.h);
  for (let y = 0; y < mask.h; y++) {
    for (let x = 0; x < mask.w; x++) {
      if (mask.get(x, y)) {
        const c = fillBottom && y >= capH / 2 ? fillBottom : fill;
        glyph.set(x + pad, y + pad, c);
      }
    }
  }
  const layered = new Pix(out.w, out.h).blit(glyph, 0, 0);
  if (inner) layered.outline(inner, true);
  if (outer) layered.outline(outer, true);
  if (shadow) out.blit(layered.tint(shadow), 1, 1);
  out.blit(layered, 0, 0);
  return out;
}
